// Land as a dot grid, for the track record map: every city where the NEXT.io
// team has built events. Built once from Natural Earth's 1:50m land (public
// domain, via the world-atlas package) with the same method as the next-2027
// hub's map, widened west to take in Las Vegas: longitude -127 to 42 and
// latitude 12 to 60, equirectangular with longitude scaled by cos 36 degrees;
// one cell is 1.3 units and the board is 105 x 36 cells. '1' is a land dot.
export const MAP = { lon0: -127, lon1: 42, lat0: 12, lat1: 60, k: Math.cos(36 * Math.PI / 180), cell: 1.3, cols: 105, rows: 36 }
export const MAP_W = MAP.cols * MAP.cell
export const MAP_H = MAP.rows * MAP.cell
// board position of a place, in the same units as the dot grid
export const project = (lat, lon) => [(lon - MAP.lon0) * MAP.k, MAP.lat1 - lat]
